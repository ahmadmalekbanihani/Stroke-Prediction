import streamlit as st
import pandas as pd
import joblib


st.set_page_config(
    page_title="Stroke Prediction",
    page_icon="🧠"
)


@st.cache_resource
def load_model():

    model = joblib.load(
        "stroke_model.pkl"
    )

    return model


model = load_model()


st.title(
    "🧠 Stroke Prediction System"
)

st.write(
    "Enter patient information "
    "to predict the stroke class."
)

st.warning(
    "Educational machine-learning "
    "project only. Not a medical "
    "diagnostic system."
)


gender = st.selectbox(
    "Gender",
    [
        "Male",
        "Female",
        "Other"
    ]
)


age = st.number_input(
    "Age",
    min_value=0.0,
    max_value=120.0,
    value=45.0
)


hypertension = st.selectbox(
    "Hypertension",
    [
        0,
        1
    ],
    format_func=lambda x:
        "Yes" if x == 1 else "No"
)


heart_disease = st.selectbox(
    "Heart Disease",
    [
        0,
        1
    ],
    format_func=lambda x:
        "Yes" if x == 1 else "No"
)


ever_married = st.selectbox(
    "Ever Married",
    [
        "Yes",
        "No"
    ]
)


work_type = st.selectbox(
    "Work Type",
    [
        "Private",
        "Self-employed",
        "Govt_job",
        "children",
        "Never_worked"
    ]
)


residence_type = st.selectbox(
    "Residence Type",
    [
        "Urban",
        "Rural"
    ]
)


avg_glucose_level = st.number_input(
    "Average Glucose Level",
    min_value=0.0,
    max_value=400.0,
    value=100.0
)


bmi = st.number_input(
    "BMI",
    min_value=0.0,
    max_value=100.0,
    value=28.0
)


smoking_status = st.selectbox(
    "Smoking Status",
    [
        "never smoked",
        "formerly smoked",
        "smokes",
        "Unknown"
    ]
)


if st.button("Predict"):

    patient = pd.DataFrame([
        {
            "gender":
                gender,

            "age":
                age,

            "hypertension":
                hypertension,

            "heart_disease":
                heart_disease,

            "ever_married":
                ever_married,

            "work_type":
                work_type,

            "Residence_type":
                residence_type,

            "avg_glucose_level":
                avg_glucose_level,

            "bmi":
                bmi,

            "smoking_status":
                smoking_status
        }
    ])


    prediction = model.predict(
        patient
    )[0]


    if prediction == 1:

        st.error(
            "Prediction: Stroke Class (1)"
        )

    else:

        st.success(
            "Prediction: No Stroke Class (0)"
        )


    if hasattr(
        model.named_steps["model"],
        "predict_proba"
    ):

        probability = (
            model.predict_proba(
                patient
            )[0][1]
        )

        st.write(
            "Predicted Class-1 Probability:",
            f"{probability:.2%}"
        )