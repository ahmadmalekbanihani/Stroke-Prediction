X = df.drop(columns=["stroke", "id"])

y = df["stroke"]

print("X shape:", X.shape)
print("y shape:", y.shape)

X.head()

X_train, X_test, y_train, y_test = train_test_split(
    X,
    y,
    test_size=0.20,
    random_state=42,
    stratify=y
)

print("Training size:", X_train.shape)
print("Testing size:", X_test.shape)

print("\nTraining classes:")
print(y_train.value_counts())

print("\nTesting classes:")
print(y_test.value_counts())

numerical_features = [
    "age",
    "avg_glucose_level",
    "bmi"
]

binary_features = [
    "hypertension",
    "heart_disease"
]

categorical_features = [
    "gender",
    "ever_married",
    "work_type",
    "Residence_type",
    "smoking_status"
]

numerical_pipeline = Pipeline(
    steps=[
        (
            "imputer",
            SimpleImputer(strategy="median")
        ),
        (
            "scaler",
            StandardScaler()
        )
    ]
)

categorical_pipeline = Pipeline(
    steps=[
        (
            "imputer",
            SimpleImputer(
                strategy="constant",
                fill_value="Unknown"
            )
        ),
        (
            "onehot",
            OneHotEncoder(
                handle_unknown="ignore",
                sparse_output=False
            )
        )
    ]
)

preprocessor = ColumnTransformer(
    transformers=[
        (
            "numerical",
            numerical_pipeline,
            numerical_features
        ),

        (
            "binary",
            "passthrough",
            binary_features
        ),

        (
            "categorical",
            categorical_pipeline,
            categorical_features
        )
    ]
)

X_train_processed = preprocessor.fit_transform(X_train)

X_test_processed = preprocessor.transform(X_test)

print(
    "Training after preprocessing:",
    X_train_processed.shape
)

print(
    "Testing after preprocessing:",
    X_test_processed.shape
)

oversampler = RandomOverSampler(
    random_state=42
)

X_train_balanced, y_train_balanced = (
    oversampler.fit_resample(
        X_train_processed,
        y_train
    )
)

print("Before oversampling:")

print(y_train.value_counts())

print("After oversampling:")

print(
    pd.Series(y_train_balanced).value_counts()
)

before = y_train.value_counts().sort_index()

after = (
    pd.Series(y_train_balanced)
    .value_counts()
    .sort_index()
)

x = np.arange(2)

width = 0.35

plt.figure(figsize=(8, 5))

plt.bar(
    x - width / 2,
    before.values,
    width,
    label="Before Oversampling"
)

plt.bar(
    x + width / 2,
    after.values,
    width,
    label="After Oversampling"
)

plt.xticks(
    x,
    ["No Stroke (0)", "Stroke (1)"]
)

plt.xlabel("Class")
plt.ylabel("Number of Samples")

plt.title(
    "Class Distribution Before and After Oversampling"
)

plt.legend()

plt.show()

logistic_model = LogisticRegression(
    max_iter=2000,
    random_state=42
)

logistic_model.fit(
    X_train_balanced,
    y_train_balanced
)

logistic_predictions = logistic_model.predict(
    X_test_processed
)

logistic_accuracy = accuracy_score(
    y_test,
    logistic_predictions
)

logistic_precision = precision_score(
    y_test,
    logistic_predictions,
    zero_division=0
)

logistic_recall = recall_score(
    y_test,
    logistic_predictions,
    zero_division=0
)

logistic_f1 = f1_score(
    y_test,
    logistic_predictions,
    zero_division=0
)

print("LOGISTIC REGRESSION")

print(
    "Accuracy:",
    round(logistic_accuracy, 4)
)

print(
    "Precision:",
    round(logistic_precision, 4)
)

print(
    "Recall:",
    round(logistic_recall, 4)
)

print(
    "F1 Score:",
    round(logistic_f1, 4)
)

